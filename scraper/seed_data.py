def seed_database():
    """Seed the database with fallback phone data."""
    init_db()
    session = get_session()
    count = 0

    for data in FALLBACK_PHONES:
        existing = session.query(Phone).filter_by(gsmarena_url=data["gsmarena_url"]).first()
        if not existing:
            phone = Phone(**data)
            session.add(phone)
            count += 1

    session.commit()
    session.close()
    print(f"[SEED] Inserted {count} phones into database.")
    return count


